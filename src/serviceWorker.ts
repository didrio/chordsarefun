/**
 * The service worker that makes the app work offline (T33), as text. The Vite build writes it to `dist/sw.js`
 * with the list of built files and a version (a hash of them), so every deploy is a new worker. Kept as text,
 * like the limiter's worklet (`limiterWorkletSource`): no bundling step, no imports, and `vite.config.ts` can
 * build it without DOM types. Pure: the build and the tests call it; `pwa.ts` registers the result.
 *
 * What it does, in DAW terms "the app is saved with the project, and the newest copy wins when you're online":
 * - **The page** (`./`, `index.html`): network first, so whoever is online always gets the latest deploy. If the
 *   network fails or takes longer than `PAGE_TIMEOUT_MS` (plane wifi), the saved copy opens instead.
 * - **Everything else it saved** (scripts, styles, icons): from the cache first; Vite's hashed `assets/` never
 *   change under one name. New hashed files are saved as they're fetched.
 * - A new worker takes over right away (`skipWaiting`) and deletes the old copies: there are no lazily loaded
 *   chunks, so a tab still running the old version never needs a file the old copy had. That tab then shows
 *   "A new version is ready" (`pwa.ts`), and reloading gets the new one.
 */

/** Built files that aren't needed to run the app (share card, crawler files, Cloudflare's config). */
const NOT_CACHED = new Set(['sw.js', '_headers', 'og.png', 'robots.txt', 'sitemap.xml', 'licenses.txt'])

/** How long the page waits for the network before opening the saved copy. */
export const PAGE_TIMEOUT_MS = 3000

/**
 * What the worker saves, as URLs relative to it, from the built files' paths (relative to `dist`, with `/`).
 * `index.html` is saved as `./`, the URL people open; source maps and dotfiles are left out.
 */
export function precacheList(files: string[]): string[] {
  return files
    .filter((f) => !NOT_CACHED.has(f) && !f.endsWith('.map') && !f.split('/').some((part) => part.startsWith('.')))
    .map((f) => (f === 'index.html' ? './' : f))
    .sort()
}

/** The worker's script for these saved URLs (`precacheList`) and this version (any short id string). */
export function serviceWorkerSource(precache: string[], version: string): string {
  return `// chords are fun: offline copy of the app (generated by the build, see src/serviceWorker.ts)
const VERSION = ${JSON.stringify(version)}
const PRECACHE = ${JSON.stringify(precache)}
const PAGE_TIMEOUT_MS = ${PAGE_TIMEOUT_MS}
const CACHE = 'chords-' + VERSION
const scope = new URL('./', self.location.href)
const saved = new Set(PRECACHE.map((u) => new URL(u, scope).href))

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      // 'reload': straight from the server, never an older copy from the browser's HTTP cache.
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(new URL(u, scope).href, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('chords-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

/** The app's own page: the scope itself or its index.html (any query). Other pages (licenses.txt) aren't ours. */
const isAppPage = (url) => url.pathname === scope.pathname || url.pathname === scope.pathname + 'index.html'

async function page(event) {
  const cache = await caches.open(CACHE)
  // By URL: a navigation Request can't be copied with options. 'no-cache': ask the server, never a stale copy.
  const network = fetch(event.request.url, { cache: 'no-cache' }).then((res) => {
    if (res.ok) void cache.put(new URL('./', scope).href, res.clone())
    return res
  })
  // Keep the worker alive until the newest page is saved, even when the saved copy answered first.
  event.waitUntil(network.then(() => {}, () => {}))
  const late = new Promise((resolve) => setTimeout(resolve, PAGE_TIMEOUT_MS, null))
  try {
    const res = await Promise.race([network, late])
    if (res) return res
  } catch {
    // Offline: the saved copy below.
  }
  return (await cache.match(new URL('./', scope).href, { ignoreVary: true })) ?? network
}

async function file(request) {
  const cache = await caches.open(CACHE)
  // ignoreVary: the saved copy was fetched without the Origin header a module script sends (Vary: Origin).
  const hit = await cache.match(request, { ignoreVary: true })
  if (hit) return hit
  const res = await fetch(request)
  if (res.ok && new URL(request.url).pathname.startsWith(scope.pathname + 'assets/')) void cache.put(request, res.clone())
  return res
}

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== scope.origin) return // analytics and the like: the browser's business
  if (request.mode === 'navigate') {
    if (isAppPage(url)) event.respondWith(page(event))
    return
  }
  url.search = ''
  url.hash = ''
  if (saved.has(url.href) || url.pathname.startsWith(scope.pathname + 'assets/')) event.respondWith(file(request))
})
`
}

/** A short version id from the built files' paths and contents (FNV-1a over both: any change = new id). */
export function buildVersion(files: { path: string; bytes: Uint8Array }[]): string {
  let h1 = 0x811c9dc5
  let h2 = 0x01000193
  const feed = (b: number) => {
    h1 = Math.imul(h1 ^ b, 0x01000193) >>> 0
    h2 = Math.imul(h2 ^ b, 0x5bd1e995) >>> 0
  }
  for (const f of [...files].sort((a, b) => (a.path < b.path ? -1 : 1))) {
    for (let i = 0; i < f.path.length; i++) feed(f.path.charCodeAt(i) & 0xff)
    feed(0)
    for (const b of f.bytes) feed(b)
    feed(0)
  }
  return h1.toString(16).padStart(8, '0') + h2.toString(16).padStart(8, '0')
}
